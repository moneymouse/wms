"""Private paper photographs on a persistent filesystem, with retryable deletion."""
import hashlib
import logging
import os
import re
import stat
from contextlib import contextmanager
from datetime import datetime
from pathlib import Path
from uuid import uuid4


EXTENSIONS = {"image/jpeg": "jpg", "image/png": "png", "image/webp": "webp"}
IDENTIFIER = re.compile(r"[A-Za-z0-9_-]{1,64}\Z")
FILE_NAME = re.compile(r"[A-Za-z0-9_-]{1,64}\.(?:jpg|png|webp)\Z")


class PhotoStorageError(OSError):
    pass


def root_path():
    configured = os.environ.get("PAPER_PHOTO_ROOT")
    return Path(configured or Path(__file__).resolve().parents[1] / "uploads" / "paper_intakes").absolute()


def _parts(storage_path):
    if not isinstance(storage_path, str):
        raise PhotoStorageError("Invalid photo storage path")
    parts = storage_path.split("/")
    if len(parts) != 2 or not IDENTIFIER.fullmatch(parts[0]) or not FILE_NAME.fullmatch(parts[1]):
        raise PhotoStorageError("Invalid photo storage path")
    return parts


@contextmanager
def _directory(intake_uid=None, create=False):
    root = root_path()
    if root.resolve() != root:
        raise PhotoStorageError("Photo storage directory contains a symbolic link")
    if create:
        root.mkdir(parents=True, exist_ok=True)
    root_fd = os.open(root, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    child_fd = None
    try:
        if intake_uid is None:
            yield root_fd
        else:
            if not IDENTIFIER.fullmatch(intake_uid):
                raise PhotoStorageError("Invalid intake identifier")
            if create:
                try:
                    os.mkdir(intake_uid, mode=0o700, dir_fd=root_fd)
                except FileExistsError:
                    pass
            child_fd = os.open(intake_uid, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=root_fd)
            yield child_fd
    finally:
        if child_fd is not None:
            os.close(child_fd)
        os.close(root_fd)


def _read_from(directory, filename):
    descriptor = os.open(filename, os.O_RDONLY | os.O_NOFOLLOW, dir_fd=directory)
    with os.fdopen(descriptor, "rb") as stream:
        if not stat.S_ISREG(os.fstat(stream.fileno()).st_mode):
            raise PhotoStorageError("Photo is not a regular file")
        return stream.read()


def save_bytes(intake_uid, photo_uid, mime_type, data):
    """Write atomically; a migration retry verifies rather than overwrites old files."""
    if mime_type not in EXTENSIONS or not IDENTIFIER.fullmatch(intake_uid) or not IDENTIFIER.fullmatch(photo_uid):
        raise PhotoStorageError("Invalid photograph metadata")
    filename = f"{photo_uid}.{EXTENSIONS[mime_type]}"
    storage_path = f"{intake_uid}/{filename}"
    digest = hashlib.sha256(data).hexdigest()
    with _directory(intake_uid, create=True) as directory:
        try:
            existing = _read_from(directory, filename)
        except FileNotFoundError:
            existing = None
        if existing is not None:
            if len(existing) != len(data) or hashlib.sha256(existing).hexdigest() != digest:
                raise PhotoStorageError("Existing photo differs from the database source")
        else:
            temporary = f".{photo_uid}.{uuid4().hex}.tmp"
            try:
                descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600, dir_fd=directory)
                with os.fdopen(descriptor, "wb") as stream:
                    stream.write(data)
                    stream.flush()
                    os.fsync(stream.fileno())
                # Identifiers are generated by the server; concurrent retries can
                # safely install identical bytes using the same deterministic key.
                os.replace(temporary, filename, src_dir_fd=directory, dst_dir_fd=directory)
                os.fsync(directory)
            finally:
                try:
                    os.unlink(temporary, dir_fd=directory)
                except FileNotFoundError:
                    pass
        written = _read_from(directory, filename)
        if len(written) != len(data) or hashlib.sha256(written).hexdigest() != digest:
            raise PhotoStorageError("Photo verification failed after writing")
    return {"storage_path": storage_path, "size_bytes": len(data), "sha256": digest}


def read_bytes(photo):
    intake_uid, filename = _parts(photo.storage_path)
    with _directory(intake_uid) as directory:
        data = _read_from(directory, filename)
    if len(data) != photo.size_bytes or hashlib.sha256(data).hexdigest() != photo.sha256:
        raise PhotoStorageError("Stored photo failed its integrity check")
    return data


def file_size(storage_path):
    """Return actual bytes for an owned regular file, or None when missing/unsafe."""
    try:
        intake_uid, filename = _parts(storage_path)
        with _directory(intake_uid) as directory:
            info = os.stat(filename, dir_fd=directory, follow_symlinks=False)
            return info.st_size if stat.S_ISREG(info.st_mode) else None
    except (OSError, ValueError):
        return None


def iter_files():
    """Count only regular managed files; never follow links into other folders."""
    try:
        with _directory() as root_fd:
            with os.scandir(root_fd) as directories:
                names = [entry.name for entry in directories if IDENTIFIER.fullmatch(entry.name) and entry.is_dir(follow_symlinks=False)]
            for intake_uid in names:
                with _directory(intake_uid) as directory:
                    with os.scandir(directory) as files:
                        for entry in files:
                            if FILE_NAME.fullmatch(entry.name) and entry.is_file(follow_symlinks=False):
                                yield f"{intake_uid}/{entry.name}", entry.stat(follow_symlinks=False).st_size
    except FileNotFoundError:
        return


def delete_file(storage_path):
    intake_uid, filename = _parts(storage_path)
    try:
        with _directory(intake_uid) as directory:
            info = os.stat(filename, dir_fd=directory, follow_symlinks=False)
            if not stat.S_ISREG(info.st_mode):
                raise PhotoStorageError("Refusing to remove a non-regular photo")
            os.unlink(filename, dir_fd=directory)
            os.fsync(directory)
    except FileNotFoundError:
        pass


def queue_photo_deletion(session, photos, packing_list_uid=None):
    from data.intake import PaperPhotoCleanupTable

    for photo in photos:
        _parts(photo.storage_path)
        if session.get(PaperPhotoCleanupTable, photo.storage_path) is None:
            session.add(PaperPhotoCleanupTable(
                storage_path=photo.storage_path, size_bytes=photo.size_bytes,
                packing_list_uid=packing_list_uid,
                created_at=datetime.now().isoformat(timespec="seconds"),
            ))


def drain_photo_cleanup(factory=None, packing_list_uid=None, storage_paths=None):
    """Delete committed tombstones. Missing files make retries idempotent."""
    from data import database
    from data.intake import IntakePhotoTable, PaperPhotoCleanupTable

    factory = factory or database.SessionFactory
    result = {"deleted_files": 0, "deleted_bytes": 0, "pending_files": 0}
    with factory() as session:
        query = session.query(PaperPhotoCleanupTable.storage_path)
        if packing_list_uid is not None:
            query = query.filter_by(packing_list_uid=packing_list_uid)
        if storage_paths is not None:
            storage_paths = set(storage_paths)
            for path in storage_paths:
                _parts(path)
            query = query.filter(PaperPhotoCleanupTable.storage_path.in_(storage_paths))
        paths = [row[0] for row in query.all()]
    for path in paths:
        with factory() as session:
            record = session.query(PaperPhotoCleanupTable).filter_by(storage_path=path).with_for_update().first()
            if record is None:
                continue
            try:
                if session.query(IntakePhotoTable.uid).filter_by(storage_path=path).first() is not None:
                    raise PhotoStorageError("Photo still has an active reference")
                actual_size = file_size(path)
                delete_file(path)
                session.delete(record)
                session.commit()
                result["deleted_files"] += 1 if actual_size is not None else 0
                result["deleted_bytes"] += actual_size or 0
            except OSError:
                session.rollback()
                logging.getLogger(__name__).exception("Paper photo cleanup needs retry")
                result["pending_files"] += 1
    return result
